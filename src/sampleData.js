function buildYoutubeUrl(video) {
  if (/^[a-zA-Z0-9_-]{11}$/.test(video.id)) {
    return `https://www.youtube.com/watch?v=${video.id}`;
  }
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(`${video.title} ${video.channel}`)}`;
}

export function scoreVideo(video) {
  const viewSubRatio = video.views / Math.max(video.subscribers, 1);
  const ratioScore = Math.min(100, viewSubRatio * 8);
  const velocityScore = Math.min(100, video.vph / 500);
  const freshScore = Math.max(20, 100 - video.publishedHoursAgo / 18);
  const lowSubScore = video.subscribers < 100000 ? 100 : video.subscribers < 250000 ? 72 : 45;
  const engagementRate = ((video.likes + video.comments) / Math.max(video.views, 1)) * 100;
  const engagementScore = Math.min(100, engagementRate * 18);
  const score =
    ratioScore * 0.3 +
    velocityScore * 0.25 +
    freshScore * 0.15 +
    lowSubScore * 0.15 +
    engagementScore * 0.1 +
    80 * 0.05;
  return Math.round(Math.max(1, Math.min(99, score)));
}

export function formatCompact(value) {
  if (value >= 100000000) return `${(value / 100000000).toFixed(1)}亿`;
  if (value >= 10000) return `${(value / 10000).toFixed(value >= 100000 ? 0 : 1)}万`;
  if (value >= 1000) return `${(value / 1000).toFixed(1)}k`;
  return String(value);
}

export function formatAge(hours) {
  if (hours < 24) return `${hours} 小时前`;
  const days = Math.round(hours / 24);
  if (days < 30) return `${days} 天前`;
  return `${Math.round(days / 30)} 个月前`;
}
